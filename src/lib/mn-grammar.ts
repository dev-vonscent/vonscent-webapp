/**
 * Тоонд залгах гарах тийн ялгал (-аас/-ээс/-оос/-өөс).
 *
 * Дагавар нь тооны ДУУДЛАГЫН сүүлийн үгийн эгшгээр сонгогдоно: 3 «гурав» →
 * 3-аас, 1 «нэг» → 1-ээс, 20 «хорь» → 20-оос, 40 «дөч» → 40-өөс.
 * «Таны сонгосон 3-аас 1 ширхэг үлдсэн» гэх мэт мессежүүдэд.
 */
const BY_UNIT = [
  "ээс",
  "ээс",
  "оос",
  "аас",
  "өөс",
  "аас",
  "аас",
  "оос",
  "аас",
  "өөс",
];
const BY_TEN = [
  "",
  "аас",
  "оос",
  "аас",
  "өөс",
  "аас",
  "аас",
  "аас",
  "аас",
  "өөс",
];

export function numAblative(n: number): string {
  const v = Math.abs(Math.trunc(n));
  let suffix: string;
  if (v === 0)
    suffix = "ээс"; // тэг
  else if (v % 10 !== 0) suffix = BY_UNIT[v % 10];
  else if (v % 100 !== 0) suffix = BY_TEN[(v / 10) % 10];
  else suffix = "аас"; // зуу, мянга, сая
  return `${n}-${suffix}`;
}
