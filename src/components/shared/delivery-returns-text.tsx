import { DELIVERY_END_HOUR, DISPATCH_HOUR } from "@/lib/time";

/**
 * Бүх барааны нийтлэг «Хүргэлт» / «Буцаалт» текст (клиентийн Текст А,
 * 2026-09 UG) — кодонд, санд биш. Дан ус ба бэлэн багцын дэлгэрэнгүйд
 * хоёр тусдаа accordion (task 5). Цагууд `lib/time.ts`-ийн дүрмээс — дүрэм
 * өөрчлөгдвөл энд ч дагаж өөрчлөгдөнө.
 */

/** «Хүргэлт» — захиалгын цаг, хүргэлтийн хуваарь, орон нутаг. */
export function DeliveryText() {
  const hours = `${DISPATCH_HOUR}:00–${DELIVERY_END_HOUR}:00`;
  return (
    <>
      Тухайн өдрийн 00:00 цаг хүртэлх захиалга маргааш өдрийнх нь {hours} цагийн
      хооронд хүргэгдэнэ. 00:00 цагаас хойших захиалга маргааш өдрийнх нь
      захиалгад орох тул нөгөөдрийнх нь {hours} цагийн хооронд хүргэгдэнэ. Орон
      нутагт мөн адил энэ цагийн хуваарийн дагуу унаанд тавигдах бөгөөд
      хэрэглэгчийн гарт очих хугацаа нь байршлын хол ойроос хамааран харилцан
      адилгүй байна.
    </>
  );
}

/** «Буцаалт» — decant барааны буцаалтын нөхцөл. */
export function ReturnsText() {
  return (
    <>
      Decant бараа (өөрийн эх савнаас таслаж гаргаж авсан) тул сав баглаа
      боодлын эвдрэл гэмтэл, асгарч гоожсон, захиалсан бараанаас өөр бараа
      хүргэгдсэн гэх мэт шалтгаанаас бусад (шалтгаангүйгээр буцаах, хэрэглэгчийн
      хувийн сонирхол, таалалд нийцээгүй зэрэг) шалтгаанаар буцаалт хийх
      боломжгүйг анхаарна уу.
    </>
  );
}

/**
 * Хоёулаа нэг догол мөрөнд — нэмэлт барааны хуудасны «Хүргэлт» хэсэг
 * (өмнөх шигээ, task 5-ын хамрах хүрээнээс гадуур).
 */
export function DeliveryReturnsText() {
  return (
    <>
      <DeliveryText /> <ReturnsText />
    </>
  );
}
