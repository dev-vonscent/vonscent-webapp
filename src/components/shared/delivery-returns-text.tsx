import { DELIVERY_END_HOUR, DISPATCH_HOUR } from "@/lib/time";

/**
 * «Хүргэлт ба буцаалт» — бүх барааны нийтлэг текст (клиентийн Текст А,
 * 2026-09 UG). Дан усны хуудас болон бэлэн багцын хуудас хоёулаа үүнийг
 * хэрэглэнэ. Цагууд `lib/time.ts`-ийн дүрмээс — дүрэм өөрчлөгдвөл энд ч
 * дагаж өөрчлөгдөнө.
 */
export function DeliveryReturnsText() {
  const hours = `${DISPATCH_HOUR}:00–${DELIVERY_END_HOUR}:00`;
  return (
    <>
      Тухайн өдрийн 00:00 цаг хүртэлх захиалга маргааш өдрийнх нь {hours} цагийн
      хооронд хүргэгдэнэ. 00:00 цагаас хойших захиалга маргааш өдрийнх нь
      захиалгад орох тул нөгөөдрийнх нь {hours} цагийн хооронд хүргэгдэнэ. Орон
      нутагт мөн адил энэ цагийн хуваарийн дагуу унаанд тавигдах бөгөөд
      хэрэглэгчийн гарт очих хугацаа нь байршлын хол ойроос хамааран харилцан
      адилгүй байна. Decant бараа (өөрийн эх савнаас таслаж гаргаж авсан) тул
      сав баглаа боодлын эвдрэл гэмтэл, асгарч гоожсон, захиалсан бараанаас өөр
      бараа хүргэгдсэн гэх мэт шалтгаанаас бусад (шалтгаангүйгээр буцаах,
      хэрэглэгчийн хувийн сонирхол, таалалд нийцээгүй зэрэг) шалтгаанаар буцаалт
      хийх боломжгүйг анхаарна уу.
    </>
  );
}
