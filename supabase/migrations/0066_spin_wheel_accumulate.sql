-- Азын хүрд: купон хуримтлагдана (клиент, 2026-09-07 — docs/lucky-wheel.md §0).
--
-- Клиент 0053-ын гурван тагийг цуцаллаа:
--   №1 «ашиглагдаагүй хүрдний купон нэг дор нэг л байна» → купон хуримтлагдана.
--   №4 «хувиар хөнгөлөх купонд дээд хязгаар»            → хязгааргүй.
--   №5 «2мл багц сард 3, дууссан бол шилжинэ»            → админ гараар удирдана.
--
-- Гурвуулаа зардлыг нэмэгдүүлдэг. Хуримтлагддаг болсноор хэрэглэгч захиалга
-- бүрт **сүүлд хожсоноо биш, барьж байгаагаас хамгийн сайныг** хэрэглэдэг тул
-- 80,000₮ захиалга тутмын хүлээгдэх хөнгөлөлт 2,580₮ → 5,410₮ болно
-- (docs/lucky-wheel.md §5.1). Нөхөн төлбөр нь 10% купоны жинг дөрөв дахин
-- бууруулах — 4.0% → 1.0%, дээд хязгаараа алдсан тул одоо тэр нь хүрдэн дэх
-- цорын ганц хязгааргүй шагнал (500,000₮ захиалга дээр 50,000₮).
--
-- Логик өөрчлөгдөхгүй: `spin_wheel()` эдгээрийг бүгдийг өгөгдлөөс уншдаг
-- (`v_single`, `max_discount`, `monthly_cap`, `fallback_slot`) тул RPC-г
-- хөндөхгүй. `coupons.max_discount` багана ба `validate_coupon()`-ий таглалт
-- мөн хэвээр — гараар үүсгэсэн купонд хэрэгтэй; зөвхөн хүрдний шагналууд
-- түүнийг хэрэглэхээ болино.
--
-- **Хуучин утгаар хамгаалсан update:** migrate.ts бүх файлыг дахин дахин
-- ажиллуулдаг тул шинэчлэл бүр 0053-ын seed утгыг л сольдог. Админ жинг
-- дараа нь өөрөө өөрчилбөл (`/admin/lucky-wheel`) энэ migration түүнийг дарж
-- бичихгүй — 0048/0027-ын зарчим: систем админы шийдвэрийг дарахгүй.

-- ── 1. Купон хуримтлагдана (§5 таг №1 цуцлагдав) ───────────────────────
update settings
   set value = jsonb_set(value, '{singleActiveCoupon}', 'false'::jsonb)
 where key = 'spin'
   and value->>'singleActiveCoupon' = 'true';

-- ── 2. Хувиар хөнгөлөх купоны дээд хязгаар авагдав (таг №4) ────────────
--
-- Доод хязгаар нь 0053-д аль хэдийн 0 байсан — клиент түүнийг баталгаажуулсан.
-- `prize_terms` (prize-reveal.tsx) `maxDiscount` null үед бүрэн ажиллана:
-- «Доод хязгааргүй» гэж бичээд дээд хязгаарын мөрийг зурахгүй.
update spin_wheel_prizes set max_discount = null
 where slot = 3 and kind = 'coupon_percent' and max_discount = 10000;
update spin_wheel_prizes set max_discount = null
 where slot = 6 and kind = 'coupon_percent' and max_discount = 15000;

-- ── 3. 2мл багц: автомат таг ба шилжилт авагдав (таг №5) ───────────────
--
-- Ингэснээр 2мл-ийн зардал эргэлтийн тоотой шугаман, дээд хязгааргүй өснө
-- (10,000 эргэлт/сар → 20 багц → 640,000₮ — §5.3). Энэ бол хүрдэнд үлдсэн
-- цорын ганц автоматгүй эрсдэл: админ `/admin/lucky-wheel`-ийн «хүргээгүй
-- шагнал» тоог сар бүр хараад жинг буулгах эсвэл салбарыг унтраана.
update spin_wheel_prizes
   set monthly_cap = null, fallback_slot = null
 where slot = 2 and kind = 'bundle' and monthly_cap = 3 and fallback_slot = 4;

-- ── 4. Шинэ жин (§2) ───────────────────────────────────────────────────
--
-- Ховор купонуудаас чөлөөлөгдсөн 4.0 нэгж голдуу пойнт руу очив: пойнт бол
-- сарын тагтай (`monthlyPointCap`) цорын ганц шагнал тул хуримтлагдахгүй,
-- хожилт тутамд хамгийн хямд. 10,000₮-ийг бас бууруулсан нь ≥100,000₮
-- захиалга дээр «хамгийн сайн купон» өрсөлдөөнд хоёрдугаарт ордог учраас.
--
--   слот  шагнал        хуучин → шинэ
--     1   500V            33.8 → 36.0
--     3   5%              21.0 → 21.0  (хөндөгдөөгүй)
--     4   10,000₮          7.0 →  6.0
--     5   1,000V          16.0 → 17.0
--     6   10%              4.0 →  1.0   ← гол өөрчлөлт
--     7   5,000₮          13.0 → 13.8
--   Гранд 0.2% · Ховор 12.0% · Энгийн 87.8%
update spin_wheel_prizes set weight = 36.0 where slot = 1 and weight = 33.8;
update spin_wheel_prizes set weight =  6.0 where slot = 4 and weight =  7.0;
update spin_wheel_prizes set weight = 17.0 where slot = 5 and weight = 16.0;
update spin_wheel_prizes set weight =  1.0 where slot = 6 and weight =  4.0;
update spin_wheel_prizes set weight = 13.8 where slot = 7 and weight = 13.0;

-- ── 5. Шинэ суулгацын анхдагч ──────────────────────────────────────────
--
-- 0053-ын `insert ... on conflict do nothing` нь хоосон өгөгдлийн санд хуучин
-- утгыг суулгах тул дээрх update-ууд тэр тохиолдолд ч ажиллана (файлууд
-- дараалан явдаг). Тусад нь seed хийх шаардлагагүй.

comment on column spin_wheel_prizes.monthly_cap is
  'Глобал сарын хязгаар. null = хязгааргүй. 2мл багц (слот 2) 2026-09-07-оос '
  'хойш null — админ гараар удирдана (docs/lucky-wheel.md §5.3).';
