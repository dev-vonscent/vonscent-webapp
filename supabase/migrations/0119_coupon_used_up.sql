-- Админы «Урамшуулал» хуудасны төлвийн шүүлтүүр (Идэвхтэй / Ашигласан /
-- Дууссан). «Ашигласан» = нийт хязгаартаа хүрсэн — хоёр баганыг харьцуулдаг
-- тул PostgREST шүүлтүүрээр бичих боломжгүй. Хадгалагдсан тооцоолсон багана
-- нь `used_count` өөрчлөгдөх бүрт өөрөө шинэчлэгдэнэ.
--
-- Дүрэм нь хэрэглэгчийн «Миний купон»-ы `couponStatus`-тай ижил:
-- ашигласан нь хугацаа дууссанаас давамгайлна.

alter table coupons
  add column if not exists used_up boolean
  generated always as (max_uses is not null and used_count >= max_uses) stored;
