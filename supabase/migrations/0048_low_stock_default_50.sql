-- Доод хязгаарын анхдагчийг 20ml → 50ml (src/lib/constants.ts: DEFAULT_LOW_STOCK_ML).
--
-- 0004-д тавьсан 20ml нь ганц 20ml decant-ын хэмжээ байсан: боломжит үлдэгдэл
-- 20ml болтол сэрэмжлүүлэг асдаггүй, тэр үед 20ml-ийн ганц захиалга бүтэн
-- үлдэгдлийг дуусгана. Гаальд саатах, тээвэрлэх хугацааг бодоход дахин
-- захиалахад орой байв.
--
-- Зөвхөн **шинэ** мөрд үйлчилнэ: одоо байгаа барааны хязгаарыг дарж бичихгүй —
-- админ тэдгээрийг гараар тохируулсан байж болно (0027 гараар үнэ тогтоох
-- зарчимтай ижил: систем админы шийдвэрийг дарахгүй).
--
-- restock_inventory (0047) шинэ inventory мөрийг `values (p_product, 0)`-оор
-- үүсгэдэг тул энэ багана нь default-аасаа утгаа авдаг — өөрөөр хэлбэл энэ
-- өөрчлөлт зөвхөн формын анхдагч биш, бодит нөлөөтэй.

alter table inventory
  alter column low_stock_ml set default 50;

comment on column inventory.low_stock_ml is
  'Боломжит үлдэгдэл (available_ml) үүнээс доош ороход бараа «Бага» төлөвт '
  'орно. Бараа тус бүрээр админ өөрчилнө; анхдагч 50ml.';
