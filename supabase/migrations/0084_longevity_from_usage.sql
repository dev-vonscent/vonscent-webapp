-- «Хэрэглэх нөхцөл»-д суусан барилтын өгүүлбэрийг `longevity` багана руу нүүлгэв.
--
-- 0083-аар талбар үүсэхээс өмнө барилтыг хэлэх цорын ганц газар нь
-- `usage_description`-ийн сүүлчийн өгүүлбэр байсан: «… 8–10 цаг тогтоно.»
-- Одоо түүнд зориулсан багана байгаа тул нэг өгөгдөл хоёр газар байх
-- шаардлагагүй — үлдээвэл хоёр нь салж, аль нь үнэн болох нь мэдэгдэхгүй
-- болно.
--
-- Хэлбэрүүд (бүгд өгүүлбэрийн ТӨГСГӨЛД):
--   «8–10 цаг тогтоно.»              → «8–10 цаг»
--   «8 цаг орчим тогтоно.»           → «8 цаг орчим»
--   «10 цаг ба түүнээс дээш тогтоно.» → «10+ цаг»
--   «Арьсан дээр 7–9 цаг тогтоно.»   → «7–9 цаг» (өгүүлбэр бүтнээрээ хасагдана)
--
-- Загвар нь «тоо + цаг … тогтоно.» гэж ЗААВАЛ мөрийн төгсгөлд таарах ёстой.
-- Зүгээр «тогтоно» гэсэн үг хангалтгүй: нэг барааны тайлбарт «… ветиверийн ул
-- суурин дээр тогтоно» гэж үнэрийн бүтцийг өгүүлсэн байдаг — тэр нь барилт
-- биш бөгөөд энэ дүрэмд огт таарахгүй.
--
-- Хоёр үйлдэл нь ӨӨР ХАМРАХ ХҮРЭЭТЭЙ, зориуд:
--   • өгүүлбэр нь таарсан БҮХ бараанаас хасагдана — клиент давхардлыг
--     бүрмөсөн арилгахыг хүссэн;
--   • `longevity` нь ЗӨВХӨН хоосон байхад бөглөгдөнө (`coalesce`) — админ
--     аль хэдийн гараар бичсэн утга нь тайлбараас уншсан таамгаас үргэлж
--     дээр, түүнийг дарж бичих нь өгөгдөл устгасантай адил.
-- Тиймээс гараар бичсэн бараан дээр ч давхардсан өгүүлбэр нь арилна.

update products p
   set longevity = coalesce(
         p.longevity,
         case
           when parsed.m[3] = 'орчим'  then parsed.m[1] || ' цаг орчим'
           when parsed.m[3] is not null then parsed.m[1] || '+ цаг'
           when parsed.m[2] is not null then parsed.m[1] || '–' || parsed.m[2] || ' цаг'
           else parsed.m[1] || ' цаг'
         end
       ),
       -- Өгүүлбэрийг БҮТНЭЭР нь хасна: `[^.]*` цэг давж чадахгүй тул
       -- өмнөх өгүүлбэрт хүрэхгүй.
       usage_description = btrim(
         regexp_replace(parsed.u, '\s*[^.]*тогтоно\.\s*$', '')
       )
  from (
    select
      id,
      usage_description as u,
      regexp_match(
        usage_description,
        '([0-9]+)\s*(?:–|—|-)?\s*([0-9]+)?\s*цаг\s*(ба\s+түүнээс\s+дээш|орчим)?\s*тогтоно\.\s*$'
      ) as m
    from products
    where usage_description ~ '[0-9]+\s*(?:–|—|-)?\s*[0-9]*\s*цаг[^.]*тогтоно\.\s*$'
  ) parsed
 where p.id = parsed.id
   and parsed.m is not null;
