-- Барааны ҮНЭР БАРИЛТ (longevity) — «арьсан дээр хэр удаан тогтох вэ».
--
-- Эрчим (0078 `sillage`) нь үнэр хэр ХОЛ мэдрэгдэхийг хэлдэг; барилт нь хэр
-- УДААН байхыг хэлнэ. Хоёр өөр шинж: Sauvage EDT нь хол мэдрэгддэг ч 4 цагийн
-- дараа алга болдог, харин олон Extrait ойрхон ч бүтэн өдөр тогтоно.
--
-- Хаалттай жагсаалт биш, ЧӨЛӨӨТ ТЕКСТ: админ барааныхаа тайланг уншаад
-- «4-6 цаг», «8+ цаг», «өдөржин» гэх мэтээр өөрөө бичнэ. Хэмжээг нь системд
-- битүүмжлэх нь (сул/дундаж/хүчтэй) админы мэддэг нарийвчлалыг алдагдуулна —
-- үнэ гараар бичигддэгтэй яг адил зарчим.
--
-- null / хоосон = админ хараахан бичээгүй; дэлгүүр тэр мөрийг харуулахгүй.

alter table products
  add column if not exists longevity text;

comment on column products.longevity is
  'Үнэр барилт — админы гараар бичсэн чөлөөт текст (ж: «4-6 цаг»). null = бичээгүй.';
